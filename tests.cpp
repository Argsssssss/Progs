string uint_to_str(u_int64_t mes_byte){
    string mes(8,char(NULL));
    for(int i = 0; i < 8; i++){
        mes[i] |= (mes_byte >> 64 - ((i + 1) * 8)) & 0x7F;
    }
    return mes;
}

LR_blocks_32_bits usig64_to_two_usig32(u_int64_t block){
    LR_blocks_32_bits buff;
    buff._L = block >> 32;
    buff._R = block & 0xFFFFFFFF;
    return buff;
}

